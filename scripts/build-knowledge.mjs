// Builds Sparky's knowledge from workers/chat/knowledge.md (the repo mirror of the Confluence wiki).
// Everything above "## 0." is for the team and is dropped. Any line marked **Confirm** or **Hold** is
// dropped too, so unapproved facts never reach the model. Run with --check to fail when the output is stale.
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../workers/chat/knowledge.md', import.meta.url);
const target = new URL('../workers/chat/src/knowledge.generated.ts', import.meta.url);

export function approvedKnowledge(markdown) {
  const text = markdown.replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const start = text.search(/^## 0\./m);
  if (start === -1) throw new Error('knowledge.md needs a "## 0." section');
  return text
    .slice(start)
    .split('\n')
    .filter((line) => !/\*\*(Confirm|Hold)\b/i.test(line))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const body = approvedKnowledge(readFileSync(source, 'utf8'));
const output = `// Generated by scripts/build-knowledge.mjs from workers/chat/knowledge.md. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(body)};\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // Missing counts as stale.
  }
  if (current !== output) {
    console.error('Sparky knowledge is out of date. Run: npm run chat:knowledge');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
  console.log(`Wrote ${body.length} characters of approved knowledge.`);
}
